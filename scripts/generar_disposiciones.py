"""Generates V15__disposiciones_de_planta.sql: lays out every floor of the demo catalog with the
layout assigned to its building (see disposiciones/), checks the result, and writes the UPDATEs.

Run from the back folder:
    python3 scripts/generar_disposiciones.py            writes the migration
    python3 scripts/generar_disposiciones.py --ascii    also prints every floor as text
    python3 scripts/generar_disposiciones.py --json f   also dumps the plans to f

Ids and codes are kept, so existing bookings and blocks keep pointing to the same spaces.
"""
import json
import sys
from pathlib import Path

import generar_catalogo as catalogo
from disposiciones import REGISTRO
from disposiciones.modelo import APOYO, EXTERIOR, NUCLEO, PASILLO, NoEntra, PisoDatos, validar
from disposiciones.textos import completar

# Layout of each building; a list assigns floor by floor, top floor first. Torre Callao stays as
# the wireframes draw it. A floor that does not fit its layout tries the ones in RESPALDO.
ASIGNACION = {
    "Torre Callao": "PASILLO_CENTRAL",
    "Nodo Palermo": "PEINE",
    "Distrito Norte": "NUCLEO_CENTRAL",
    "Casa Barracas": "EN_L",
    "Polo Tecnológico": "PEINE",
    "Estación Retiro": "NUCLEO_CENTRAL",
    "Estudio Almagro": "EN_L",
    "Sede Constitución": "PASILLO_CENTRAL",
    "Sede Avellaneda": ["PEINE", "EN_L"],
    "Ribera Puerto Madero": "NUCLEO_CENTRAL",
    "Ribera Tigre": "EN_L",
    "Ribera Barracas": ["PASILLO_CENTRAL", "PEINE"],
    "Casa Lumen": ["EN_L", "PEINE", "EN_L"],
    "Delta Centro": "NUCLEO_CENTRAL",
    "Delta Quilmes": ["PEINE", "EN_L"],
}

RESPALDO = ["PEINE", "PASILLO_CENTRAL"]

DESTINO = Path(__file__).resolve().parent.parent / "src/main/resources/db/migration/V15__disposiciones_de_planta.sql"
SIMBOLO = {PASILLO: "=", NUCLEO: "#", APOYO: "+", EXTERIOR: "~"}


def q(value):
    return catalogo.q(value)


def pisos():
    for edificio in catalogo.nombres_de_edificios():
        for numero, cubiculos, salas, amenities in catalogo.pisos_de(edificio):
            ventanas = [w for w in catalogo.ventanas_de(numero, amenities).split(",") if w]
            yield PisoDatos(edificio, numero, catalogo.nombre_piso(numero), cubiculos, catalogo.SALAS[salas],
                            catalogo.servicios_de(amenities), amenities, ventanas)


def disposicion_de(piso, indice):
    asignada = ASIGNACION.get(piso.edificio, "PASILLO_CENTRAL")
    return asignada[indice % len(asignada)] if isinstance(asignada, list) else asignada


def disponer(piso, codigo):
    candidatas = [codigo] + [c for c in RESPALDO if c != codigo]
    for candidata in candidatas:
        try:
            plano = REGISTRO[candidata].disponer(piso)
        except NoEntra as motivo:
            print(f"  {piso.edificio} · {piso.nombre}: no entra en {candidata} ({motivo})")
            continue
        if candidata != codigo:
            print(f"    queda en {candidata}")
        return plano
    raise SystemExit(f"{piso.edificio} · {piso.nombre} no entra en ninguna disposición")


def planificar():
    planos, indice, anterior = [], 0, None
    for piso in pisos():
        indice = indice + 1 if piso.edificio == anterior else 0
        anterior = piso.edificio
        plano = disponer(piso, disposicion_de(piso, indice))
        validar(plano, piso)
        for espacio in plano.espacios:
            completar(espacio, plano, piso)
        planos.append((piso, plano))
    return planos


def sql(planos):
    out = [
        "-- Generated by scripts/generar_disposiciones.py. Lays out every floor with its building's layout.",
        "-- Spaces keep their id and code, so bookings and blocks are not affected.",
        "",
    ]
    for piso, plano in planos:
        piso_ref = (f"(SELECT p.id FROM pisos p JOIN edificios e ON e.id = p.edificio_id "
                    f"WHERE e.nombre = {q(piso.edificio)} AND p.numero = {piso.numero})")
        out.append(f"-- {piso.edificio} · {piso.nombre}: {REGISTRO[plano.disposicion].ETIQUETA}")
        out.append(
            f"UPDATE pisos SET disposicion = {q(plano.disposicion)}, plano_columnas = {plano.columnas}, "
            f"plano_filas = {plano.filas}, ventanas = {q(','.join(plano.ventanas))} WHERE id = {piso_ref};"
        )
        for e in plano.espacios:
            r = e.rect
            out.append(
                f"UPDATE espacios SET plano_x = {r.x}, plano_y = {r.y}, plano_ancho = {r.ancho}, plano_alto = {r.alto}, "
                f"ventana = {q(e.ventana)}, orientacion = {q(e.orientacion)}, ubicacion = {q(e.ubicacion)}, "
                f"descripcion = {q(e.descripcion)}, "
                f"equipamiento = {q(json.dumps(e.equipamiento, ensure_ascii=False))}::jsonb "
                f"WHERE piso_id = {piso_ref} AND codigo = {q(e.codigo)};"
            )
        for s in plano.servicios:
            r = s.rect
            out.append(
                f"UPDATE servicios_piso SET plano_x = {r.x}, plano_y = {r.y}, plano_ancho = {r.ancho}, "
                f"plano_alto = {r.alto} WHERE piso_id = {piso_ref} AND nombre = {q(s.nombre)};"
            )
        out.append(f"DELETE FROM areas_plano WHERE piso_id = {piso_ref};")
        for a in plano.areas:
            r = a.rect
            out.append(
                "INSERT INTO areas_plano (piso_id, tipo, etiqueta, plano_x, plano_y, plano_ancho, plano_alto) "
                f"VALUES ({piso_ref}, {q(a.tipo)}, {q(a.etiqueta)}, {r.x}, {r.y}, {r.ancho}, {r.alto});"
            )
        out.append("")
    return "\n".join(out)


def ascii(piso, plano):
    """The floor as text, one character per column: C cubicle, S room, s service, = corridor,
    # core, + support, ~ terrace, | window."""
    grilla = [["."] * plano.columnas for _ in range(plano.filas)]

    def pintar(rect, simbolo):
        for y in range(rect.y, rect.y2):
            for x in range(rect.x, rect.x2):
                grilla[y][x] = simbolo

    for a in plano.areas:
        pintar(a.rect, SIMBOLO[a.tipo])
    for s in plano.servicios:
        pintar(s.rect, "s")
    for e in plano.espacios:
        pintar(e.rect, "C" if e.tipo == "CUBICULO" else "S")
        grilla[e.rect.y][e.rect.x] = "|" if e.ventana else "["
    titulo = f"{piso.edificio} · {piso.nombre} · {REGISTRO[plano.disposicion].ETIQUETA} · {plano.columnas}x{plano.filas}"
    return "\n".join([titulo] + ["  " + "".join(fila) for fila in grilla])


def a_json(planos):
    return [{
        "edificio": piso.edificio, "piso": piso.nombre, "disposicion": plano.disposicion,
        "columnas": plano.columnas, "filas": plano.filas, "ventanas": plano.ventanas,
        "espacios": [{"codigo": e.codigo, "tipo": e.tipo, **vars(e.rect), "ventana": e.ventana,
                      "orientacion": e.orientacion, "ubicacion": e.ubicacion} for e in plano.espacios],
        "servicios": [{"nombre": s.nombre, "tipo": s.tipo, **vars(s.rect)} for s in plano.servicios],
        "areas": [{"tipo": a.tipo, "etiqueta": a.etiqueta, **vars(a.rect)} for a in plano.areas],
    } for piso, plano in planos]


def main(args):
    planos = planificar()
    with open(DESTINO, "w", encoding="utf-8", newline="\n") as f:
        f.write(sql(planos))
    if "--ascii" in args:
        for piso, plano in planos:
            print(ascii(piso, plano) + "\n")
    if "--json" in args:
        Path(args[args.index("--json") + 1]).write_text(json.dumps(a_json(planos), ensure_ascii=False, indent=1))
    cuenta = {}
    for _, plano in planos:
        cuenta[plano.disposicion] = cuenta.get(plano.disposicion, 0) + 1
    print(f"{len(planos)} pisos válidos:", ", ".join(f"{REGISTRO[c].ETIQUETA} {n}" for c, n in cuenta.items()))


if __name__ == "__main__":
    main(sys.argv[1:])
